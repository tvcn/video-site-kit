#!/usr/bin/env python3
"""Build a GitHub Pages-ready folder from the local prototype."""
from __future__ import annotations

import json
import os
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "v2" / "prototype"
OUT = ROOT / "v2" / "dist"


def link_or_copy(source: Path, target: Path) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    try:
        os.link(source, target)
    except OSError:
        shutil.copy2(source, target)


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    shutil.copy2(SRC / "tvcn-ui-v2.html", OUT / "index.html")
    shutil.copy2(SRC / "404.html", OUT / "404.html")
    shutil.copy2(SRC / "robots.txt", OUT / "robots.txt")
    (OUT / ".nojekyll").write_text("", encoding="utf-8")

    manifest = json.loads((SRC / "manifest.webmanifest").read_text(encoding="utf-8"))
    manifest["start_url"] = "./"
    (OUT / "manifest.webmanifest").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    sw = (SRC / "sw.js").read_text(encoding="utf-8")
    sw = sw.replace('"./tvcn-ui-v2.html"', '"./index.html"')
    (OUT / "sw.js").write_text(sw, encoding="utf-8")

    not_found = (SRC / "404.html").read_text(encoding="utf-8")
    not_found = not_found.replace('href="/tvcn-ui-v2.html#/search"', 'href="/#/search"')
    not_found = not_found.replace('href="/tvcn-ui-v2.html#/sites"', 'href="/#/sites"')
    not_found = not_found.replace('href="/tvcn-ui-v2.html"', 'href="/"')
    (OUT / "404.html").write_text(not_found, encoding="utf-8")

    src_assets = SRC / "assets"
    for source in src_assets.rglob("*"):
        if source.is_file():
            link_or_copy(source, OUT / "assets" / source.relative_to(src_assets))

    static_dir = ROOT / "v2" / "static"
    if static_dir.exists():
        for source in static_dir.rglob("*"):
            if source.is_file():
                link_or_copy(source, OUT / source.relative_to(static_dir))

    deploy_note = """# TVCN Pages build

This folder is generated by `build/make-release.py` from `v2/prototype`.

- `index.html` is the app entry.
- `assets/` carries photos, diagrams, and 42 MP3 files.
- `manifest.webmanifest` and `sw.js` enable install/offline after an HTTP(S) deploy.
- `404.html` is the GitHub Pages fallback.
- `article/<id>/` and `en/article/<id>/` are static article pages (836 total).
- `sitemap.xml` lists 840 same-host URLs; each subsite has a one-URL sitemap.
- Keep `robots.txt` and `.nojekyll`.

Before uploading, add `CNAME` (`tvcn.org`) only after DNS is pointed at Pages.
Analytics, Search Console verification, and the real contact mailbox are still open.
"""
    (OUT / "README-DEPLOY.md").write_text(deploy_note, encoding="utf-8")

    files = [p for p in OUT.rglob("*") if p.is_file()]
    size = sum(p.stat().st_size for p in files)
    print(f"OK release: {len(files)} files, {size} bytes, {OUT}")


if __name__ == "__main__":
    main()
